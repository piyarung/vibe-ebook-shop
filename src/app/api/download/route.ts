// Helper to ensure all strings passed to pdf-lib StandardFonts are 100% WinAnsi safe (0x20 - 0x7E)
function toWinAnsiSafe(text?: string, fallback: string = ''): string {
  if (!text) return fallback;
  const sanitized = text
    .split('')
    .map((char) => {
      const code = char.charCodeAt(0);
      return code >= 32 && code <= 126 ? char : '';
    })
    .join('')
    .replace(/\s+/g, ' ')
    .trim();

  return sanitized || fallback;
}

function getSafeBookTitle(rawTitle: string, bookId?: string): string {
  if (!rawTitle) rawTitle = '';
  if (rawTitle.includes('Media Player') || bookId === 'book-1') {
    return '90s Retro Media Player PRO - User & Developer Guide';
  }
  if (rawTitle.includes('Tarot') || bookId === 'book-2') {
    return 'Rider-Waite 3-Card Tarot Reading App - Guide & Manual';
  }
  if (rawTitle.includes('Task Manager') || bookId === 'book-3') {
    return 'SQLite Task Manager PRO (Futuristic Edition) - Guide & Manual';
  }
  const ascii = toWinAnsiSafe(rawTitle, '');
  return ascii || 'Vibe Coding E-book Digital Edition';
}

